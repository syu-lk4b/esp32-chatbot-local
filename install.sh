#!/usr/bin/env bash
# One-shot setup for 小奇 (XiaoQi), the ES3C28P voice-chat robot, on an Apple Silicon Mac.
#
# Usage: ./install.sh [--no-flash] [--autostart] [--skip-models] [-h|--help]
#   --no-flash     configure and build the firmware but don't flash the board
#   --autostart    install a LaunchAgent that runs start.sh at login
#   --skip-models  don't pre-download the Whisper / Qwen3-TTS weights now
#
# Safe to re-run: existing server/.env, firmware secrets.h and SearXNG settings are kept.
# Non-interactive use: set NONINTERACTIVE=1 plus WIFI_SSID, WIFI_PASS and optionally
# CHAT_HOST, LLM_BACKEND, LLM_URL, LLM_MODEL, USER_LOCATION.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
SERVER="${ROOT}/server"
FIRMWARE="${ROOT}/firmware"
SEARXNG="${ROOT}/searxng"
SEARXNG_REPO="https://github.com/searxng/searxng.git"
SEARXNG_COMMIT="81371861f67226091d1c4df2e3908a11d3b54eb9"  # tested with settings.template.yml
VOICE_PORT=8765
LAUNCH_AGENT="${HOME}/Library/LaunchAgents/com.xiaoqi.voicechat.plist"

FLASH=1
AUTOSTART=0
MODELS=1
for arg in "$@"; do
  case "${arg}" in
    --no-flash) FLASH=0 ;;
    --autostart) AUTOSTART=1 ;;
    --skip-models) MODELS=0 ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown option: ${arg}" >&2; exit 2 ;;
  esac
done

say() { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
info() { printf '    %s\n' "$*"; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

ask() {  # ask VAR "prompt" "default" [secret]
  local var="$1" prompt="$2" default="${3:-}" secret="${4:-}" reply=""
  if [[ -n "${!var:-}" ]]; then return; fi
  if [[ "${NONINTERACTIVE:-0}" == "1" ]]; then
    [[ -n "${default}" ]] || die "${var} is required in NONINTERACTIVE mode"
    printf -v "${var}" '%s' "${default}"
    return
  fi
  if [[ -n "${secret}" ]]; then
    read -r -s -p "    ${prompt}: " reply; echo
  else
    read -r -p "    ${prompt}${default:+ [${default}]}: " reply
  fi
  printf -v "${var}" '%s' "${reply:-${default}}"
}

# ---------------------------------------------------------------- 1. prerequisites
say "Checking prerequisites"
[[ "$(uname -s)" == "Darwin" && "$(uname -m)" == "arm64" ]] || die "needs an Apple Silicon Mac (MLX runs Whisper and Qwen3-TTS on the GPU)"
command -v brew >/dev/null || die "Homebrew not found; install it from https://brew.sh and re-run"
missing=()
command -v ffmpeg >/dev/null || missing+=(ffmpeg)
command -v git >/dev/null || missing+=(git)
PYTHON="${PYTHON:-$(command -v python3.11 || true)}"
[[ -n "${PYTHON}" ]] || missing+=(python@3.11)
if ((${#missing[@]})); then
  info "installing with Homebrew: ${missing[*]}"
  brew install "${missing[@]}"
  PYTHON="${PYTHON:-$(brew --prefix python@3.11)/bin/python3.11}"
fi
info "python: ${PYTHON} ($("${PYTHON}" --version))"

# ---------------------------------------------------------------- 2. voice server
say "Setting up the voice server"
[[ -d "${SERVER}/.venv" ]] || "${PYTHON}" -m venv "${SERVER}/.venv"
"${SERVER}/.venv/bin/pip" install -q --upgrade pip
"${SERVER}/.venv/bin/pip" install -q -r "${SERVER}/requirements.txt" platformio
info "dependencies installed"

if [[ ! -f "${SERVER}/.env" ]]; then
  ask LLM_BACKEND "LLM backend: openai (LM Studio / any OpenAI-compatible) or ollama" "openai"
  if [[ "${LLM_BACKEND}" == "ollama" ]]; then
    ask LLM_URL "Ollama URL" "http://127.0.0.1:11434"
    ask LLM_MODEL "Ollama model" "qwen3:30b-a3b-instruct-2507-q4_K_M"
  else
    ask LLM_URL "OpenAI-compatible base URL" "http://127.0.0.1:1234/v1"
    models="$(curl -sf -m 3 "${LLM_URL}/models" | "${PYTHON}" -c 'import json,sys;print(" ".join(m["id"] for m in json.load(sys.stdin)["data"] if "embed" not in m["id"]))' 2>/dev/null || true)"
    [[ -n "${models}" ]] && info "models on that server: ${models}"
    ask LLM_MODEL "LLM model id" "${models%% *}"
    [[ -n "${LLM_MODEL}" ]] || die "no model id; load a chat model in LM Studio (Developer tab → Start Server) and re-run"
  fi
  ask USER_LOCATION "Your city (default location for weather/news)" "上海"
  token="$("${PYTHON}" -c 'import secrets;print(secrets.token_urlsafe(18))')"
  cat > "${SERVER}/.env" <<EOF
# Generated by install.sh — keep private (gitignored).
VOICE_TOKEN=${token}
VOICE_PORT=${VOICE_PORT}
LLM_BACKEND=${LLM_BACKEND}
LLM_URL=${LLM_URL}
LLM_MODEL=${LLM_MODEL}
USER_LOCATION=${USER_LOCATION}
TTS_ENGINE=qwen3
# For thinking/reasoning models in LM Studio, "none" turns thinking off (2-3x faster replies).
LLM_REASONING_EFFORT=${LLM_REASONING_EFFORT:-}
EOF
  chmod 600 "${SERVER}/.env"
  info "wrote server/.env"
else
  info "server/.env exists, keeping it"
fi
TOKEN="$(sed -n 's/^VOICE_TOKEN=//p' "${SERVER}/.env")"
[[ -n "${TOKEN}" ]] || die "server/.env has no VOICE_TOKEN"

if [[ "${MODELS}" == "1" ]]; then
  say "Downloading speech models (first run only, a few GB)"
  # Run from server/ so voice_server is importable for its Settings defaults.
  (cd "${SERVER}" && "${SERVER}/.venv/bin/python" -) <<'EOF'
import numpy as np, mlx_whisper
from mlx_audio.tts.utils import load_model
from voice_server.config import Settings
s = Settings()
mlx_whisper.transcribe(np.zeros(16000, np.float32), path_or_hf_repo=s.whisper_model, verbose=None)
print("    whisper ready:", s.whisper_model)
if s.tts_engine == "qwen3":
    load_model(s.qwen_tts_model)
    print("    qwen3-tts ready:", s.qwen_tts_model)
EOF
fi
if grep -q '^TTS_ENGINE=piper' "${SERVER}/.env" && [[ ! -f "${SERVER}/models/zh_CN-huayan-medium.onnx" ]]; then
  "${SERVER}/.venv/bin/python" -m piper.download_voices --download-dir "${SERVER}/models" zh_CN-huayan-medium
fi

# ---------------------------------------------------------------- 3. local web search
say "Setting up SearXNG (local web search)"
if [[ ! -d "${SEARXNG}/src/.git" ]]; then
  git clone -q "${SEARXNG_REPO}" "${SEARXNG}/src"
fi
git -C "${SEARXNG}/src" fetch -q --depth 1 origin "${SEARXNG_COMMIT}" 2>/dev/null || true
git -C "${SEARXNG}/src" checkout -q "${SEARXNG_COMMIT}"
[[ -d "${SEARXNG}/.venv" ]] || "${PYTHON}" -m venv "${SEARXNG}/.venv"
"${SEARXNG}/.venv/bin/pip" install -q --upgrade pip setuptools wheel
"${SEARXNG}/.venv/bin/pip" install -q -r "${SEARXNG}/src/requirements.txt"
"${SEARXNG}/.venv/bin/pip" install -q --no-build-isolation -e "${SEARXNG}/src"
if [[ ! -f "${SEARXNG}/settings.yml" ]]; then
  secret="$("${PYTHON}" -c 'import secrets;print(secrets.token_hex(32))')"
  sed "s/__GENERATED_BY_INSTALL__/${secret}/" "${SEARXNG}/settings.template.yml" > "${SEARXNG}/settings.yml"
  chmod 600 "${SEARXNG}/settings.yml"
  info "wrote searxng/settings.yml"
else
  info "searxng/settings.yml exists, keeping it"
fi

# ---------------------------------------------------------------- 4. firmware
say "Configuring the firmware"
SECRETS="${FIRMWARE}/include/secrets.h"
if [[ ! -f "${SECRETS}" ]]; then
  iface="$(route -n get default 2>/dev/null | awk '/interface:/{print $2}')"
  mac_ip="$(ipconfig getifaddr "${iface:-en0}" 2>/dev/null || true)"
  ask WIFI_SSID "2.4 GHz Wi-Fi name (the board can't use 5 GHz)" ""
  ask WIFI_PASS "Wi-Fi password" "" secret
  ask CHAT_HOST "This Mac's LAN IP (reserve it in your router's DHCP)" "${mac_ip}"
  [[ -n "${WIFI_SSID}" && -n "${CHAT_HOST}" ]] || die "Wi-Fi name and Mac IP are required"
  # Escape for a C string literal.
  esc() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }
  cat > "${SECRETS}" <<EOF
#pragma once
// Generated by install.sh — keep private (gitignored).
#define WIFI_SSID "$(esc "${WIFI_SSID}")"
#define WIFI_PASS "$(esc "${WIFI_PASS}")"
#define CHAT_SERVER "http://${CHAT_HOST}:${VOICE_PORT}"
// Must equal VOICE_TOKEN in server/.env
#define CHAT_TOKEN "${TOKEN}"
EOF
  chmod 600 "${SECRETS}"
  info "wrote firmware/include/secrets.h (server http://${CHAT_HOST}:${VOICE_PORT})"
else
  info "firmware secrets.h exists, keeping it"
  grep -q "\"${TOKEN}\"" "${SECRETS}" || info "warning: CHAT_TOKEN in secrets.h differs from server/.env VOICE_TOKEN"
fi

PIO="${SERVER}/.venv/bin/pio"
info "building firmware (first build downloads the ESP32 toolchain)"
(cd "${FIRMWARE}" && "${PIO}" run 2>&1) | grep -E "RAM:|Flash:|SUCCESS|FAILED|[Ee]rror" || true
if [[ "${FLASH}" == "1" ]]; then
  port="$(ls /dev/cu.usbmodem* 2>/dev/null | head -1 || true)"
  if [[ -n "${port}" ]]; then
    info "flashing ${port}"
    (cd "${FIRMWARE}" && "${PIO}" run -t upload --upload-port "${port}" 2>&1) | grep -E "SUCCESS|FAILED|[Ee]rror" || true
  else
    info "no board on /dev/cu.usbmodem*; plug it in and run: (cd firmware && ../server/.venv/bin/pio run -t upload)"
  fi
fi

# ---------------------------------------------------------------- 5. autostart
if [[ "${AUTOSTART}" == "1" ]]; then
  say "Installing LaunchAgent"
  mkdir -p "$(dirname "${LAUNCH_AGENT}")"
  cat > "${LAUNCH_AGENT}" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>com.xiaoqi.voicechat</string>
  <key>ProgramArguments</key><array><string>${ROOT}/start.sh</string></array>
  <key>RunAtLoad</key><true/>
  <!-- start.sh exits after backgrounding the servers; keep launchd from killing them -->
  <key>AbandonProcessGroup</key><true/>
  <key>StandardOutPath</key><string>${ROOT}/server/launchd.log</string>
  <key>StandardErrorPath</key><string>${ROOT}/server/launchd.log</string>
</dict></plist>
EOF
  launchctl unload "${LAUNCH_AGENT}" 2>/dev/null || true
  launchctl load "${LAUNCH_AGENT}"
  info "start.sh will run at login; also enable LM Studio → Settings → start server at login"
fi

say "Done"
info "start the backend:  ${ROOT}/start.sh        (stop: ./start.sh stop)"
info "the LLM server (LM Studio / Ollama) must be running with ${LLM_MODEL:-your model} loaded"
info "board: switch to AUTO and say “小奇小奇”, or hold the screen to talk"
